#!/usr/bin/env python3
"""Generate board_keepouts.scad from board-model/cec-bridge-assembled.stl.

Splits the ASCII STL into connected shells, takes each shell's bounding box and writes every
top-side part as a keep-out box in BOARD coordinates (x right, y DOWN from the top edge,
h = height above the board top). Shells belonging to the mis-placed HDMI supplier model
(they dip below the board top) are dropped: J2 is modelled by hand in enclosure.scad.
Re-run after board-model/regenerate.sh:  python3 keepouts_from_stl.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
STL = os.path.join(HERE, "board-model", "cec-bridge-assembled.stl")
OUT = os.path.join(HERE, "board_keepouts.scad")
BOARD_T = 1.6
HDMI_MODEL_BOX = (2.4, 17.6, 29.2, 40.5)  # board coords of the mis-placed J2 model

tris, cur = [], []
for line in open(STL):
    s = line.split()
    if s and s[0] == "vertex":
        cur.append((round(float(s[1]), 4), round(float(s[2]), 4), round(float(s[3]), 4)))
        if len(cur) == 3:
            tris.append(tuple(cur)); cur = []

parent = {}
def find(a):
    while parent[a] != a:
        parent[a] = parent[parent[a]]; a = parent[a]
    return a
for t in tris:
    for v in t:
        parent.setdefault(v, v)
    for a, b in ((t[0], t[1]), (t[1], t[2])):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[ra] = rb
comps = {}
for t in tris:
    comps.setdefault(find(t[0]), []).append(t)

boxes = []
for ts in comps.values():
    vs = [v for t in ts for v in t]
    x0, x1 = min(v[0] for v in vs), max(v[0] for v in vs)
    y0, y1 = min(-v[1] for v in vs), max(-v[1] for v in vs)   # board y = -model y
    z0, z1 = min(v[2] for v in vs), max(v[2] for v in vs)
    if z1 <= BOARD_T + 0.02:
        continue                                   # bare board / copper
    if (x1 - x0) < 0.6 and (y1 - y0) < 0.6:
        continue                                   # silkscreen-like slivers (LDO marking)
    hx0, hx1, hy0, hy1 = HDMI_MODEL_BOX
    inside_hdmi = x0 >= hx0 and x1 <= hx1 and y0 >= hy0 and y1 <= hy1
    if inside_hdmi and (z0 < 1.55 or z0 > 3.5):
        continue                                   # J2 supplier model shells
    boxes.append((x0, x1, y0, y1, max(z1 - BOARD_T, 0.0)))

boxes.sort(key=lambda b: (b[2], b[0]))
with open(OUT, "w") as f:
    f.write("// GENERATED by keepouts_from_stl.py from board-model/cec-bridge-assembled.stl - do not edit.\n")
    f.write("// [x0, x1, y0, y1, h]: board coords (y DOWN from top edge), h = height above board top.\n")
    f.write("// J2 (HDMI, mis-placed model) and the unmodelled J1/J3/SW1/SW2 are added in enclosure.scad.\n")
    f.write("stl_keepouts = [\n")
    for b in boxes:
        f.write("  [%.2f, %.2f, %.2f, %.2f, %.2f],\n" % b)
    f.write("];\n")
print("wrote", OUT, len(boxes), "boxes")
